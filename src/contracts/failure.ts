import { createHash } from 'node:crypto';

// Почему таксономия, а не разбор текста постфактум.
//
// Причина отказа известна ровно там, где отказ возник: пустой коммит виден по
// diff, провал проверки — по её коду выхода, отказ ревью — по его вердикту.
// Восстанавливать этот факт регулярным выражением по сообщению значит
// выбросить знание и потом угадывать его — а угадывание ошибается там, где
// текст задачи похож на текст инфраструктуры. Поэтому класс ставится в точке
// отказа, записывается вместе с попыткой и дальше используется как есть.

import type { FailureKind } from './execution.ts';

/** Отказ окружения до начала работы: попытка не засчитывается. */
export class BlockedError extends Error {
  override name = 'BlockedError';
}

/** Отказ с известным классом. Класс ставит тот, кто отказ обнаружил. */
export class TaskFailure extends Error {
  constructor(
    readonly kind: FailureKind,
    message: string,
    /**
     * Свойства, с которыми связан отказ: `bound` — объявленные задачей
     * property ID, `unbound` — названные проверкой или ревьюером, но не
     * объявленные (только для разбора, счётчик эпизода они не выбирают);
     * `classes` — классы входов, названные ревьюером; `pairs` — свойство и
     * класс одной находки.
     */
    readonly properties?: {
      bound: string[];
      unbound: string[];
      classes?: string[];
      pairs?: { property: string; inputClass: string }[];
    },
  ) {
    super(message);
    this.name = 'TaskFailure';
  }
}

/**
 * Отпечаток отказа: одинаковые сбои должны совпадать, разные — расходиться.
 *
 * Из сообщения убирается всё, что меняется от попытки к попытке, — SHA, id
 * прогонов, пути с временными каталогами, числа, время. Иначе два одинаковых
 * провала одной проверки выглядели бы как два разных, и предел одинаковых
 * повторов не сработал бы ни разу.
 */
export function failureFingerprint(kind: FailureKind, message: string) {
  const normalized = message
    .toLowerCase()
    // UUID раньше SHA: шаблон SHA съедает его восьми- и двенадцатисимвольные
    // группы, после чего целого UUID уже не видно, а середина остаётся
    // случайной — и один и тот же отказ с новым request id считался разным.
    .replace(/\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/g, '<id>')
    .replace(/\b[0-9a-f]{7,40}\b/g, '<sha>')
    .replace(/\d{4}-\d{2}-\d{2}t[\d:.]+z?/g, '<time>')
    .replace(/\/[^\s'"]*\/[^\s'"]*/g, '<path>')
    .replace(/\d+/g, '<n>')
    .replace(/\s+/g, ' ')
    .trim()
    // Предел выше всей диагностики проверки (оба потока и упавшие testcases,
    // каждое со своим лимитом): при прежних 300 символах ошибка stderr
    // оказывалась за пределом, и разные провалы получали один отпечаток.
    .slice(0, 2000);
  return createHash('sha256')
    .update(kind + '\n' + normalized)
    .digest('hex')
    .slice(0, 16);
}

