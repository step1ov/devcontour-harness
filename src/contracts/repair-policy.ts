// Таблица восстановления без node:* — её читают и движок, и чистые проекции
// (`devcontour-harness/projections`, доступные браузеру).

import type { FailureKind } from './execution.ts';

export interface RepairRule {
  /** `retry` — новая попытка той же задачи; `stop` — звать человека. */
  action: 'retry' | 'stop';
  /**
   * Сколько раз один и тот же отпечаток разрешено чинить автоматически.
   * Исчерпан — гипотез больше нет, и цикл останавливается с этой причиной.
   */
  repeats: number;
  /** Причина, которую увидит человек, когда цикл остановится. */
  explain: string;
  /**
   * Отказ повторится на любой задаче, а не только на этой: выдача
   * останавливается целиком, иначе очередь переберёт задачи одну за другой и
   * сожжёт бюджет попыток каждой на одной и той же внешней причине.
   *
   * Этим же свойством причина снимается: починив её, восстановление убирает
   * свою запись из списка блокировок, а выдача возвращается, только когда не
   * осталось ни одной. Решать это по тексту сообщения нельзя — замечание
   * ревью про «401 Unauthorized» в разрабатываемом приложении так становилось
   * отказом провайдера и останавливало работу насовсем.
   */
  blocksQueue?: boolean;
}

