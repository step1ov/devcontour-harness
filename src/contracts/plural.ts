// Русские формы существительного при числе: одна функция для всех строк
// harness, где число стоит перед словом («1 попытка», «2 попытки», «5 попыток»).
// Лист без импортов: её читают и движок, и чистые проекции (браузерный бандл).

/**
 * Три формы слова в нужном падеже: при 1 (21, 101…), при 2–4 (22–24…) и при
 * 0, 5–20 (11–14, 25–30…). Для родительного падежа («у 1 попытки», «из 2
 * попыток») это родительный единственного и дважды родительный
 * множественного: `['попытки', 'попыток', 'попыток']`.
 */
export type RuForms = readonly [one: string, few: string, many: string];

/** Форма слова при числе `n`; дробное — форма «2–4» («1,5 попытки»). */
export function ruForm(n: number, forms: RuForms): string {
  if (!Number.isInteger(n)) return forms[1];
  const abs = Math.abs(n);
  const d = abs % 10;
  const h = abs % 100;
  if (d === 1 && h !== 11) return forms[0];
  if (d >= 2 && d <= 4 && (h < 12 || h > 14)) return forms[1];
  return forms[2];
}

/** «N слово» в форме при N: `ruCount(21, ['попытка', 'попытки', 'попыток'])` — «21 попытка». */
export const ruCount = (n: number, forms: RuForms): string => `${n} ${ruForm(n, forms)}`;

