// Перестроить оглавление `skills/harness/SKILL.md` из разделов guide
// (alpha.71, E3): `node --import tsx scripts/guide-index.ts`. Тест
// `guide.test.ts` сверяет оглавление с файлами.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { guideIndex, skillsRoot } from '../src/guide/guide.ts';

const file = join(skillsRoot, 'harness', 'SKILL.md');
const start = '<!-- guide-index:start (generated by scripts/guide-index.ts) -->';
const end = '<!-- guide-index:end -->';
const text = readFileSync(file, 'utf8');
const block = `${start}\n\n${guideIndex()}\n\n${end}`;
const next = text.includes(start)
  ? text.slice(0, text.indexOf(start)) + block + text.slice(text.indexOf(end) + end.length)
  : text.replace('<!-- guide-index -->', block);
writeFileSync(file, next);
